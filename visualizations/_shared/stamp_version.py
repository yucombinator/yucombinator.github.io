#!/usr/bin/env python3
"""Stamp shared assets with a content hash.

Writes _shared/version.js (read by the engine for data/stops/busways fetches)
and appends ?v=<hash> to the shared script/style tags in every city page.
Run it before deploying; local development does not need it.

    python3 _shared/stamp_version.py

Use --check in CI to fail when the pages are not stamped with the current hash.
"""
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CITIES = sorted(p for p in ROOT.iterdir()
                if p.is_dir() and (p / "city.js").exists())

# Only runtime assets participate: copy/index changes do not need a JS cache
# bust, and version.js must not hash itself.
ASSETS = [HERE / "motion.js", HERE / "motion.css", HERE / "cities.js"] \
    + [c / "city.js" for c in CITIES]
# Data payloads use the same ?v= token, so nightly GTFS rebuilds must change it.
for city in CITIES:
    ASSETS += sorted(city.glob("data*.json"))
    ASSETS += sorted(city.glob("stops-*.json"))
    if (city / "busways.json").exists():
        ASSETS.append(city / "busways.json")

digest = hashlib.sha256()
for path in ASSETS:
    digest.update(path.read_bytes())
VERSION = digest.hexdigest()[:12]

CHECK = "--check" in sys.argv
version_path = HERE / "version.js"
if CHECK:
    if not version_path.exists():
        sys.exit("not stamped (version.js missing)")
    current = version_path.read_text()
    stamped = f"'{VERSION}'" in current
    stale = []
    for city in CITIES:
        html = (city / "index.html").read_text()
        for need in ("../_shared/motion.css", "../_shared/version.js",
                     "../_shared/cities.js", "../_shared/motion.js", "city.js"):
            if not re.search(re.escape(need) + r"\?v=" + VERSION, html):
                stale.append(f"{city.name}: {need}")
    if not stamped or stale:
        print(f"not stamped for {VERSION}", file=sys.stderr)
        for s in stale:
            print("  " + s, file=sys.stderr)
        sys.exit(1)
    print(f"stamped {VERSION}")
    sys.exit(0)

(HERE / "version.js").write_text(
    "/* Asset version for cache busting; generated by stamp_version.py. */\n"
    f"window.MOTION_VERSION = '{VERSION}';\n")

for city in CITIES:
    html = (city / "index.html").read_text()
    for need in ("../_shared/motion.css", "../_shared/version.js",
                 "../_shared/cities.js", "../_shared/motion.js", "city.js"):
        html = re.sub(re.escape(need) + r"(\?v=[^\"']*)?", need + f"?v={VERSION}", html)
    (city / "index.html").write_text(html)

print(f"stamped {VERSION}")
